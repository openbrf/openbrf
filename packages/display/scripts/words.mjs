/**
 * Writes src/words.ts: the renderer's own words, the `screenContent`
 * namespace of packages/i18n's locale files, in Swedish and English.
 *
 * The translations are kept in packages/i18n with every other text of the
 * platform, where they are translated and reviewed. That package is private
 * and this one is published, so the words are copied in rather than imported,
 * and src/words.spec.ts fails when the copy is behind the locale files.
 *
 * Run it with `pnpm --filter @openbrf/display words` after changing a word.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const localesDirectory = join(packageRoot, "..", "i18n", "src", "locales");
const target = join(packageRoot, "src", "words.ts");

function namespace(locale) {
  const file = join(localesDirectory, `${locale}.json`);
  const words = JSON.parse(readFileSync(file, "utf8")).screenContent;
  if (typeof words !== "object" || words === null || Array.isArray(words)) {
    throw new Error(`${file} has no screenContent object.`);
  }
  for (const [key, value] of Object.entries(words)) {
    if (typeof value !== "string") {
      throw new Error(
        `screenContent.${key} in ${file} is not a string. Keep the namespace flat.`,
      );
    }
  }
  return words;
}

const en = namespace("en");
const sv = namespace("sv");
const missing = Object.keys(en).filter((key) => !(key in sv));
const extra = Object.keys(sv).filter((key) => !(key in en));
if (missing.length > 0 || extra.length > 0) {
  throw new Error(
    `sv.json's screenContent must have exactly en.json's keys. Missing: ${missing.join(", ") || "none"}. Extra: ${extra.join(", ") || "none"}.`,
  );
}
// Swedish in English's key order, so the two read side by side.
const svInOrder = Object.fromEntries(
  Object.keys(en).map((key) => [key, sv[key]]),
);

const source = `// Generated by scripts/words.mjs from the screenContent namespace of
// packages/i18n/src/locales/en.json and sv.json. Do not edit it by hand:
// change the translations there and run \`pnpm --filter @openbrf/display words\`.
import type { ScreenLocale } from "./contract.ts";

const en = ${JSON.stringify(en, null, 2)} as const;

/** A word the renderer shows that is not in the document. */
export type WordKey = keyof typeof en;

/** The renderer's own words in every screen language, English the canonical one. */
export const WORDS: Readonly<
  Record<ScreenLocale, Readonly<Record<WordKey, string>>>
> = {
  en,
  sv: ${JSON.stringify(svInOrder, null, 2)},
};
`;

const options = (await resolveConfig(target)) ?? {};
writeFileSync(target, await format(source, { ...options, filepath: target }));
console.log(`Wrote ${target}`);
